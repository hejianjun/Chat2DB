ALTER TABLE TASK ALTER COLUMN TASK_PROGRESS SET DATA TYPE INT USING
    CASE
        WHEN TASK_PROGRESS IS NOT NULL
            AND REGEXP_LIKE(TRIM(TASK_PROGRESS), '^[0-9]+$')
        THEN CAST(TRIM(TASK_PROGRESS) AS INT)
        ELSE 0
    END;

ALTER TABLE TASK ALTER COLUMN TASK_PROGRESS SET DEFAULT 0;

UPDATE TASK
SET TOTAL_COUNT = TASK_PROGRESS
WHERE TASK_STATUS = 'FINISH'
  AND COALESCE(TOTAL_COUNT, 0) <= 0;
